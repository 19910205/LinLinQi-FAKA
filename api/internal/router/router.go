		protected.GET("/notifications/templates", middleware.RequirePermission(db, "system.view"), h.AdminNotificationTemplates)
		protected.POST("/notifications/templates", middleware.RequirePermission(db, "system.manage"), h.CreateAdminNotificationTemplate)
