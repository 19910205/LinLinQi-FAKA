		protected.GET("/operations/:resource", middleware.RequireOperationPermission(db), h.AdminResourceList)
		protected.POST("/operations/:resource", middleware.RequireOperationPermission(db), h.CreateAdminResource)
		protected.GET("/categories", middleware.RequireAnyPermission(db, "catalog.view", "supplier.view"), h.AdminCategories)
