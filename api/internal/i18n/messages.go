// ResolveLocale resolves the response language from a request. It prefers
// an explicit lang query parameter, then the X-Lang header, then the
// Accept-Language header; anything outside the supported locales falls back
// to simplified Chinese.
func ResolveLocale(c *gin.Context) string {
	if c == nil || c.Request == nil {
		return LocaleZH
	}
	if lang := strings.TrimSpace(c.Query("lang")); lang != "" {
		return normalizeLocale(lang)
	}
	if lang := strings.TrimSpace(c.GetHeader("X-Lang")); lang != "" {
		return normalizeLocale(lang)
	}
	accept := strings.TrimSpace(c.GetHeader("Accept-Language"))
	if accept == "" {
		return LocaleZH
	}
	parts := strings.Split(accept, ",")
	if len(parts) == 0 {
		return LocaleZH
	}
	return normalizeLocale(parts[0])
}

// Localize resolves the message identified by key for the request's
// negotiated language. When the key is missing from the active locale the
// key itself is returned, keeping messages stable for debugging. Optional
// template data supports Go template placeholders such as {{ .Min }}.
func Localize(c *gin.Context, key string, templateData ...interface{}) string {
	locale := LocaleZH
	if c != nil {
		if stored, ok := c.Get(CtxLocale); ok {
			if l, ok := stored.(string); ok && l != "" {
				locale = l
			} else {
				locale = ResolveLocale(c)
			}
		} else {
			locale = ResolveLocale(c)
		}
	}
	msg := T(locale, key)
	if len(templateData) > 0 && templateData[0] != nil {
		return Sprintf(msg, templateData[0])
	}
	return msg
}

// T returns the message for key in locale, falling back to simplified
// Chinese and finally to the key itself.
func T(locale, key string) string {
	if locale == "" {
		locale = LocaleZH
	}
	if table, ok := messages[locale]; ok {
		if msg, ok := table[key]; ok {
			return msg
		}
	}
	if locale != LocaleZH {
		if table, ok := messages[LocaleZH]; ok {
			if msg, ok := table[key]; ok {
				return msg
			}
		}
	}
	return key
}

// Sprintf fills Go template placeholders ({{ .Field }}) in the message from
// a data map or struct.
func Sprintf(msg string, data interface{}) string {
	var b strings.Builder
	b.Grow(len(msg) + 32)
	for i := 0; i < len(msg); {
		if i+2 < len(msg) && msg[i] == '{' && msg[i+1] == '{' {
			end := strings.Index(msg[i+2:], "}}")
			if end < 0 {
				b.WriteString(msg[i:])
				break
			}
			end += i + 2
			field := strings.TrimSpace(msg[i+2 : end])
			field = strings.TrimPrefix(field, ".")
			if value := fieldValue(data, field); value != "" {
				b.WriteString(value)
			}
			i = end + 2
			continue
		}
		b.WriteByte(msg[i])
		i++
	}
	return b.String()
}

func fieldValue(data interface{}, field string) string {
	switch d := data.(type) {
	case map[string]interface{}:
		if v, ok := d[field]; ok {
			return fmt.Sprintf("%v", v)
		}
	case map[string]string:
		return d[field]
	default:
		return fmt.Sprintf("%v", data)
	}
	return ""
}

func normalizeLocale(locale string) string {
	l := strings.ToLower(strings.TrimSpace(locale))
	switch {
	case strings.HasPrefix(l, "zh-tw"), strings.HasPrefix(l, "zh-hk"), strings.HasPrefix(l, "zh-mo"), strings.HasPrefix(l, "zh-hant"):
		return LocaleTW
	case strings.HasPrefix(l, "zh"):
		return LocaleZH
	case strings.HasPrefix(l, "en"):
		return LocaleEN
	default:
		return LocaleZH
	}
}
